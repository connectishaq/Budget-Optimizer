// npm run benchmarks:review
// Lists every country value marked { "verify": true } in src/data/countries/*.json
// and writes REVIEW_BENCHMARKS.md at the project root.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'src/data/countries');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort();

const show = (v) => (Array.isArray(v) ? `${v[0]} – ${v[1]}` : String(v));

function collect(node, at, out) {
  if (Array.isArray(node)) node.forEach((v, i) => collect(v, `${at}[${i}]`, out));
  else if (node && typeof node === 'object') {
    if (node.verify === true && 'value' in node) out.push({ path: at, value: node.value, note: node.note || '' });
    else for (const [k, v] of Object.entries(node)) collect(v, at ? `${at}.${k}` : k, out);
  }
}

let total = 0;
const sections = files.map((f) => {
  const data = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  const items = [];
  collect(data, '', items);
  total += items.length;
  const rows = items.map((i) => `| \`${i.path}\` | ${show(i.value)} | ${i.note.replace(/\|/g, '\\|')} |`).join('\n');
  const sources = (data.sources || []).map((s) => `- [${s.title}](${s.url})${s.usedFor ? `: ${s.usedFor}` : ''}`).join('\n');
  return `## ${data.code} · ${data.currency || 'any currency'} · last reviewed ${data.lastReviewed || '—'}

${items.length ? `${items.length} value(s) to verify.\n\n| Value | Current | Why it needs checking |\n|---|---|---|\n${rows}` : 'Nothing marked for review.'}

${sources ? `**Sources**\n\n${sources}` : '**Sources:** none listed.'}
`;
});

const md = `# Benchmarks to review

Generated by \`npm run benchmarks:review\` from \`src/data/countries/*.json\`. Do not edit by hand.

Every number below is an estimate, not a sourced fact. It is used for "typical" ranges, the
"higher than typical" hints and when savings ideas appear. Check each one against a current local
source, then remove its \`"verify": true\` wrapper (keep the plain number) and update \`lastReviewed\`.

**${total} value(s) across ${files.length} file(s).**

${sections.join('\n')}`;

fs.writeFileSync(path.join(root, 'REVIEW_BENCHMARKS.md'), md);
console.log(`REVIEW_BENCHMARKS.md: ${total} value(s) to verify across ${files.length} file(s).`);
