// npm run i18n:notes
// Collects the translators' notes (src/i18n/notes/<lang>.md) and the
// article writers' notes (src/i18n/notes/article-<page>.md) into
// TRANSLATION_NOTES.md: uncertain phrases, regional terms and figures to check.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const NAMES = { ar: 'Arabic', de: 'German', es: 'Spanish', fr: 'French', hi: 'Hindi', id: 'Indonesian', pt: 'Portuguese', ur: 'Urdu' };

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'src/i18n/notes');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.md')).sort();
const langs = files.filter((f) => !f.startsWith('article-') && !f.startsWith('guide-'));
const guideNotes = files.filter((f) => f.startsWith('guide-'));
const articles = files.filter((f) => f.startsWith('article-'));

// Each file's own headings move down two levels under its section
const body = (f) => fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim()
  .split('\n').filter((line, i) => !(i === 0 && line.startsWith('# ')))
  .map((line) => (/^#{1,4} /.test(line) ? `##${line}` : line)).join('\n').trim();

const out = [
  '# Translation notes',
  '',
  'Generated by `npm run i18n:notes` from `src/i18n/notes/`; edit those files, not this one.',
  'Everything listed here needs a native speaker or a local reviewer before launch. The legal pages',
  '(privacy policy, terms, disclaimer) need a professional legal review in every language.',
  '',
  '## Languages',
  '',
  ...langs.flatMap((f) => {
    const code = path.basename(f, '.md');
    return [`### ${NAMES[code] || code} (${code})`, '', body(f), ''];
  }),
  '## Country articles ("5 Hidden Household Expense Leaks")',
  '',
  ...articles.flatMap((f) => [`### /${path.basename(f, '.md').slice('article-'.length)}/`, '', body(f), '']),
  '## Money guides (/guides/, /ur-pk/guides/)',
  '',
  ...guideNotes.flatMap((f) => {
    const name = path.basename(f, '.md').slice('guide-'.length);
    return [`### ${name.startsWith('ur-') ? `Urdu: ${name.slice(3)}` : name}`, '', body(f), ''];
  })
].join('\n');

fs.writeFileSync(path.join(root, 'TRANSLATION_NOTES.md'), `${out.trim()}\n`);
console.log(`TRANSLATION_NOTES.md: ${langs.length} languages, ${articles.length} articles.`);
